	public function checkcategory($page, $category_id) {
		$query = $this->db->query("SELECT * FROM " . DB_PREFIX . "ocfilter_page WHERE page_id = '" . $page . "' AND category_id = '" . $category_id . "'");
		if ($query->num_rows) {
			return true;
		} else {
			return false;
		}
	}
	
	public function getPageId($url) {
		$query = $this->db->query("SELECT * FROM " . DB_PREFIX . "seo_url WHERE keyword = '" . $url . "'");
		$page_ids = array();
		if ($query->num_rows) {
			foreach ($query->rows as $result) {
				$page_ids[] = str_replace('ocfilter_page_id=','', $result['query']);
			}
		}
		
		return $page_ids;
	}
	
	public function updatecanonical($page_id, $canonical) {
		$this->db->query("UPDATE " . DB_PREFIX . "ocfilter_page_description SET canonical = '" . $this->db->escape($canonical) . "' WHERE page_id = '" . (int)$page_id . "'");
	}
